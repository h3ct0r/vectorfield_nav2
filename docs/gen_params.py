"""Generate the parameter reference pages from the generate_parameter_library YAMLs.

conf.py runs this at the start of every Sphinx build. It can also be run by hand:

    python3 docs/gen_params.py [--out docs/parameters]

Each gpl YAML is found by its unique root key and parsed with gpl's own Python package
(``GenerateCode('markdown')``); every declared parameter is rendered with gpl's
``ParameterDetailMarkdown``. Two pages are written:

* ``controller.md``: common + legacy-path keys, with headings ``FollowPath.<name>``;
* ``follower.md``: common + follower keys, unprefixed.

When a page's YAMLs do not exist yet, a short placeholder page is written instead. When the
YAMLs exist but gpl cannot be imported or parsed, the placeholder is written and the problem
is returned as a message, which conf.py reports as a Sphinx warning.
"""

import argparse
import re
import sys
from pathlib import Path

COMMON = 'vectorfield_common_params'
LEGACY = 'vectorfield_legacy_path_params'
FOLLOWER = 'vectorfield_follower_params'

PAGES = {
    'controller': {
        'title': 'Controller plugin parameters',
        'prefix': 'FollowPath.',
        'intro': (
            'All keys are declared under the controller plugin name in `controller_server`. '
            'The headings use the conventional name `FollowPath`. When the plugin is the '
            "RotationShimController's primary controller on Lyrical and later, the prefix "
            'is `FollowPath.primary_controller.`.'
        ),
        'groups': [
            (COMMON, 'Common parameters'),
            (LEGACY, 'Legacy path handling: Humble–Kilted (Gen A/B) only'),
        ],
    },
    'follower': {
        'title': 'Curve follower parameters',
        'prefix': '',
        'intro': 'Keys are declared directly on the `curve_follower` node, without a prefix.',
        'groups': [
            (COMMON, 'Common parameters'),
            (FOLLOWER, 'Follower parameters'),
        ],
    },
}

PLACEHOLDER = (
    'Parameters are generated from the generate_parameter_library YAMLs once they exist (M2).'
)
GENERATED_NOTE = '% Generated by docs/gen_params.py from the gpl YAMLs. Do not edit.'
# Points the theme's 'Edit on GitHub' link at the generator: the page has no source file.
FRONT_MATTER = (
    '---\n'
    'github_url: https://github.com/h3ct0r/vectorfield_nav2/blob/main/docs/gen_params.py\n'
    '---\n\n'
)
SKIP_DIRS = {'build', 'install', 'log', 'test', 'third_party', 'docs'}
ROOT_KEY_RE = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*)\s*:', re.MULTILINE)


def find_yamls(repo_root):
    """Map each known gpl root key to the YAML file that declares it."""
    roots = {COMMON, LEGACY, FOLLOWER}
    found = {}
    for path in sorted(repo_root.glob('vectorfield_*/**/*.yaml')):
        parts = path.relative_to(repo_root).parts
        if any(part in SKIP_DIRS or part.startswith('.') for part in parts[1:-1]):
            continue
        try:
            text = path.read_text(encoding='utf-8')
        except (OSError, UnicodeDecodeError):
            continue
        match = ROOT_KEY_RE.search(text)
        if match is None or match.group(1) not in roots:
            continue
        root = match.group(1)
        if root in found:
            raise RuntimeError(f'{root} is declared in both {found[root]} and {path}')
        found[root] = path
    return found


def render_group(yaml_path, prefix):
    """Render every parameter of one gpl YAML with gpl's ParameterDetailMarkdown."""
    from generate_parameter_library_py.generate_markdown import (
        ParameterDetailMarkdown,
        RuntimeParameterDetailMarkdown,
    )
    from generate_parameter_library_py.parse_yaml import GenerateCode

    code = GenerateCode('markdown')
    code.parse(str(yaml_path), '')
    details = [str(ParameterDetailMarkdown(p)) for p in code.declare_parameters]
    details += [str(RuntimeParameterDetailMarkdown(p)) for p in code.declare_dynamic_parameters]
    blocks = []
    for detail in details:
        # gpl emits '## <name>'; nest it under the group heading and add the node prefix.
        detail = re.sub(
            r'\A## (.+)$', lambda m: f'### `{prefix}{m.group(1)}`', detail, flags=re.MULTILINE
        )
        detail = re.sub(r'\n\*Additional Constraints:\*\s*\Z', '\n', detail)
        blocks.append(detail.strip())
    return '\n\n'.join(blocks)


def render_page(spec, repo_root, yamls):
    """Return (markdown, message) for one page; message is None unless something failed."""
    header = f'{FRONT_MATTER}# {spec["title"]}\n\n{GENERATED_NOTE}\n\n'
    missing = [root for root, _ in spec['groups'] if root not in yamls]
    if missing:
        names = ', '.join(f'`{root}`' for root in missing)
        return header + f'{PLACEHOLDER}\n\nNot found yet: {names}.\n', None
    try:
        body = [spec['intro']]
        for root, heading in spec['groups']:
            source = yamls[root].as_posix()
            body.append(f'## {heading}\n\nSource: `{source}` (root key `{root}`).')
            body.append(render_group(repo_root / yamls[root], spec['prefix']))
        return header + '\n\n'.join(body) + '\n', None
    except Exception as exc:  # noqa: BLE001 - gpl raises plain Exception subclasses
        message = f'cannot render {spec["title"]!r} with generate_parameter_library_py: {exc!r}'
        return header + f'The parameter reference could not be generated: {exc}\n', message


def write_if_changed(path, text):
    """Write text to path only when it differs, so incremental builds stay incremental."""
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        if path.read_text(encoding='utf-8') == text:
            return
    except OSError:
        pass
    path.write_text(text, encoding='utf-8')


def generate(repo_root, out_dir):
    """Write every parameter page into out_dir and return the list of problems found."""
    repo_root = Path(repo_root).resolve()
    yamls = {root: path.relative_to(repo_root) for root, path in find_yamls(repo_root).items()}
    messages = []
    for name, spec in PAGES.items():
        text, message = render_page(spec, repo_root, yamls)
        if message is not None:
            messages.append(message)
        write_if_changed(Path(out_dir) / f'{name}.md', text)
    return messages


def main(argv=None):
    """Command-line entry point."""
    docs_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--repo-root', type=Path, default=docs_dir.parent)
    parser.add_argument('--out', type=Path, default=docs_dir / 'parameters')
    args = parser.parse_args(argv)
    for message in generate(args.repo_root, args.out):
        print(f'gen_params: warning: {message}', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
